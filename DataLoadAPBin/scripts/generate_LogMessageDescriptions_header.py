#!/usr/bin/env python3
"""Embed bundled ArduPilot JSON log descriptions in a C++ header.

Usage: generate_LogMessageDescriptions_header.py <input_dir> <output_header>

The compressed Copter and Plane snapshots come from the firmware metadata
directories. Legacy JSON retains older descriptions and enum entries missing
from those snapshots. Updating any input requires rebuilding the plugin.

MSVC caps a single string literal at 16380 single-byte characters (error C2026),
so content is emitted in smaller chunks joined at runtime. Adjacent literal
concatenation would not help: that has its own 65535 byte cap.
"""
import json
import lzma
import os
import sys

# Comfortably below the MSVC limit of 16380 single-byte characters per literal.
MAX_CHUNK_BYTES = 16000


def split_utf8_chunks(content, max_bytes=MAX_CHUNK_BYTES):
    """Split content into chunks of at most max_bytes, never inside a UTF-8 character."""
    data = content.encode('utf-8')
    chunks = []
    start = 0
    while start < len(data):
        end = min(start + max_bytes, len(data))
        # Back off while the split would land on a continuation byte (0b10xxxxxx).
        while start < end < len(data) and (data[end] & 0xC0) == 0x80:
            end -= 1
        chunks.append(data[start:end].decode('utf-8'))
        start = end
    return chunks or ['']


def make_chunked_raw_strings(name, content):
    # Choose a delimiter that does not terminate a raw string in this data.
    for index in range(100):
        delim = 'APJSON' + str(index)
        if ')' + delim + '"' not in content:
            break
    else:
        raise ValueError(f'Could not choose a raw-string delimiter for {name}')
    lines = ['static const char* const ' + name + 'Chunks[] = {']
    for chunk in split_utf8_chunks(content):
        lines.append('R"' + delim + '(' + chunk + ')' + delim + '",')
    lines.extend([
        '};',
        'inline const std::string& ' + name + '()',
        '{',
        '  static const std::string joined = []() {',
        '    std::string result;',
        '    result.reserve(' + str(len(content.encode('utf-8'))) + ');',
        '    for (const char* chunk : ' + name + 'Chunks)',
        '    {',
        '      result += chunk;',
        '    }',
        '    return result;',
        '  }();',
        '  return joined;',
        '}',
    ])
    return '\n'.join(lines)


def read_json(path):
    """Decode, validate and compact a JSON snapshot for embedding."""
    opener = lzma.open if path.endswith('.xz') else open
    with opener(path, 'rt', encoding='utf-8') as source:
        content = source.read()
    data = json.loads(content)
    if not isinstance(data, dict) or not isinstance(data.get('logformats'), list):
        raise ValueError(f'{path}: expected a logformats array')
    return json.dumps(data, ensure_ascii=False, separators=(',', ':'), allow_nan=False)


def main():
    if len(sys.argv) != 3:
        print('Usage: generate_LogMessageDescriptions_header.py <input_dir> <output_header>')
        return 2
    input_dir, out_path = sys.argv[1:]
    contents = ['/* Auto-generated by generate_LogMessageDescriptions_header.py */',
                '#pragma once', '', '#include <string>', '']
    for vehicle in ('Copter', 'Plane'):
        for suffix in ('LogMessages.json.xz', 'LegacyDescriptions.json'):
            filename = vehicle + '_' + suffix
            name = 'GetEmbedded' + vehicle + ('LogMessagesJson' if suffix.startswith('LogMessages')
                                               else 'LegacyDescriptionsJson')
            contents.append(make_chunked_raw_strings(name, read_json(os.path.join(input_dir, filename))))
    os.makedirs(os.path.dirname(out_path) or '.', exist_ok=True)
    # Keep LF endings on Windows so chunk sizes stay within MSVC's byte limit.
    with open(out_path, 'w', encoding='utf-8', newline='\n') as out:
        out.write('\n'.join(contents))
    return 0


if __name__ == '__main__':
    sys.exit(main())
